function coneVolume(p: { outerMm: number; lengthMm: number; wallMm: number; coneMm: number; tipMm: number }): number {
  const r = Math.max(0.1, p.outerMm / 2 - p.wallMm);
  const tip = Math.max(0.1, p.tipMm / 2 - p.wallMm);
  const straight = Math.max(0, p.lengthMm - p.coneMm);
  return Math.PI * r * r * straight + (Math.PI * p.coneMm * (r * r + r * tip + tip * tip)) / 3;
}

