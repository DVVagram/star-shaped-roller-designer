function tubeVolume(p: { outerMm: number; lengthMm: number; wallMm: number }): number {
  const inner = Math.max(0, p.outerMm / 2 - p.wallMm);
  const straight = Math.max(0, p.lengthMm - p.outerMm / 2);
  return Math.PI * inner * inner * straight + (2 / 3) * Math.PI * inner ** 3;
}

